"""Verdict router (SCHEMA §9): combine the four agents with the §9 maths, add a 2-sentence summary (LLM via
the validators, template fallback), cache the whole verdict (§8). Python decides the label; it never raises
for LLM or agent failures."""
from __future__ import annotations

import json
import logging
import sqlite3
import threading
from contextlib import closing
from datetime import datetime, timedelta
from pathlib import Path

from backend import config
from backend.agents import fundamentals, llm, macro, sentiment
from backend.agents.validators import run_with_validation
from backend.cache import cache
from backend.db import queries
from backend.ingest import news
from backend.schemas.insights import AgentResult, MacroOutput, Verdict

log = logging.getLogger(__name__)

ROUTER_VERSION = "router-v1"
SUMMARY_AGENT = "verdict_summary"
SUMMARY_PROMPT_VERSION = "vsum-v3"
SUMMARY_PROMPT = Path(__file__).resolve().parents[1] / "agents" / "prompts" / "verdict_summary.md"
SUMMARY_MAX_TOKENS = 120
REFRESH_INTERVAL = timedelta(minutes=1)
DISCLAIMER = ("Educational outlook generated by models and AI from data up to {as_of_date}. "
              "It is not investment advice and is not a signal to trade any security.")
STANCE_VALUE = {"POSITIVE": 1, "NEGATIVE": -1, "NEUTRAL": 0}
SUMMARY_SCHEMA = {"type": "object", "properties": {"summary": {"type": "string", "minLength": 1, "maxLength": 300}},
                  "required": ["summary"]}


class NotInScope(ValueError):
    """Verdicts cover KMI-30 stocks only (SCHEMA §4.2 endpoint 11)."""


class RateLimited(RuntimeError):
    """`?refresh=true` more than once a minute for a symbol."""


def _now() -> datetime:
    """The clock; tests replace it."""
    return datetime.now(config.TZ)


# --- §9 maths (pure) ---
def strength(a: AgentResult) -> float:
    """k: quant = its confidence |2p−1| (low when the model has no edge); LLM agents 1.0 LIVE/CACHED, 0.5 TEMPLATE."""
    if a.agent == "quant":
        return float(a.evidence.get("confidence", 0.0))
    return config.STRENGTH_TEMPLATE if a.status == "TEMPLATE" else config.STRENGTH_LIVE


def combine(agents: list[AgentResult]) -> dict:
    """label, confidence, score, agreement and the agents with renormalised weights (UNAVAILABLE → weight 0)."""
    active = [a for a in agents if a.status != "UNAVAILABLE"]
    total = sum(config.AGENT_WEIGHTS[a.agent] for a in active)
    weighted = [a.model_copy(update={"weight": round(config.AGENT_WEIGHTS[a.agent] / total, 4)
                                     if a.status != "UNAVAILABLE" else 0.0}) for a in agents]
    if not active:
        return {"label": "NEUTRAL", "confidence": None, "score": 0.0, "agreement": 0.0, "agents": weighted,
                "n_agree": 0, "n_active": 0}
    score = round(sum(config.AGENT_WEIGHTS[a.agent] * STANCE_VALUE[a.stance] * strength(a) for a in active) / total, 4)
    t = config.LABEL_THRESHOLD
    label = "POSITIVE" if score >= t else "NEGATIVE" if score <= -t else "NEUTRAL"
    n_agree = sum(a.stance == label for a in active)
    agreement = round(n_agree / len(active), 4)
    confidence = None
    if label != "NEUTRAL":
        quant = next((a for a in active if a.agent == "quant"), None)
        k_quant = strength(quant) if quant and quant.stance == label else 0.0
        c = config.CONF_W_SCORE * abs(score) + config.CONF_W_AGREEMENT * agreement + config.CONF_W_QUANT * k_quant
        if any(a.status == "TEMPLATE" for a in active):
            c = min(c, config.CONF_CAP_TEMPLATE)
        if len(active) < config.MIN_ACTIVE_AGENTS:
            c = min(c, config.CONF_CAP_FEW_AGENTS)
        confidence = round(min(max(c, 0.0), config.CONF_MAX), 2)
    return {"label": label, "confidence": confidence, "score": score, "agreement": agreement, "agents": weighted,
            "n_agree": n_agree, "n_active": len(active)}


# --- Agents ---
def _unavailable(agent: str, reason: str) -> AgentResult:
    return AgentResult(agent=agent, stance="NEUTRAL", reasons=[reason], evidence={}, status="UNAVAILABLE",
                       weight=config.AGENT_WEIGHTS[agent])


def _quant_row(conn: sqlite3.Connection, code: str, as_of: str) -> sqlite3.Row | None:
    return conn.execute("""SELECT * FROM quant_predictions WHERE symbol = ? AND as_of_date <= ?
                           ORDER BY as_of_date DESC, created_at DESC LIMIT 1""", (code, as_of)).fetchone()


def quant_result(row: sqlite3.Row | None) -> AgentResult:
    """§9 quant row (no LLM): the stored §6 stance; reasons = the top 3 SHAP contributors in words."""
    if row is None:
        return _unavailable("quant", "No quant prediction: the price history is too short.")
    reasons = [f"{c['label']} of {c['value']:.2f} {'raises' if c['shap'] > 0 else 'lowers'} the model's up-probability."
               for c in json.loads(row["top_contributors"])[:3]]
    evidence = {"p_up": round(row["p_up"], 4), "confidence": round(abs(2 * row["p_up"] - 1), 4),
                "volatility_bucket": row["vol_bucket"], "regime": row["regime"], "model_version": row["model_version"]}
    return AgentResult(agent="quant", stance=row["stance"], reasons=reasons, evidence=evidence, status="LIVE",
                       weight=config.AGENT_WEIGHTS["quant"])


def _macro_output() -> MacroOutput:
    try:
        return macro.current()
    except Exception as exc:  # unreadable DB / files: macro abstains
        log.warning("macro unavailable: %s", exc)
        return macro.unavailable("Macro indicators are unavailable right now.")


def _safe(agent: str, run) -> AgentResult:
    """One agent failing (a bug or a broken row) makes it UNAVAILABLE; the verdict still renders."""
    try:
        return run()
    except Exception as exc:
        log.exception("%s agent failed", agent)
        return _unavailable(agent, f"The {agent} signal could not be computed ({type(exc).__name__}).")


# --- Summary ---
def summary_payload(symbol: str, as_of: str, combined: dict) -> dict:
    """Only the facts the summary may state (FIX-01): label, agree counts, confidence and each agent's stance and
    status. No reasons, score or weights, so any cause or other figure fails grounding or the agent-claim check."""
    p = {"symbol": symbol, "as_of_date": as_of, "label": combined["label"], "n_agree": combined["n_agree"],
         "n_active": combined["n_active"],
         "agents": [{"agent": a.agent, "stance": a.stance, "status": a.status} for a in combined["agents"]]}
    if combined["confidence"] is not None:
        p["confidence_pct"] = round(combined["confidence"] * 100)
    return p


def summary_template(p: dict) -> dict:
    """§9: "Overall outlook: {label} ({confidence}% confidence). {n_agree} of {n_active} signals agree." """
    if not p["n_active"]:
        return {"summary": f"No signals are available for {p['symbol']} as of {p['as_of_date']}, "
                           f"so the outlook is NEUTRAL."}
    conf = f"{p['confidence_pct']}% confidence" if "confidence_pct" in p else "no confidence figure for a neutral reading"
    return {"summary": f"Overall outlook: {p['label']} ({conf}). {p['n_agree']} of {p['n_active']} signals agree."}


def _summary_call(payload: dict) -> dict:
    system = SUMMARY_PROMPT.read_text(encoding="utf-8")
    return llm.generate_json(SUMMARY_AGENT, SUMMARY_PROMPT_VERSION, system, payload, SUMMARY_SCHEMA, SUMMARY_MAX_TOKENS)


# --- Cache keys ---
def _inputs(conn: sqlite3.Connection, row: sqlite3.Row, as_of: str, quant: sqlite3.Row | None,
            macro_out: MacroOutput) -> dict:
    """What the verdict depends on, with no LLM call: each agent's input hash (§8 "the agents' payload hashes")."""
    fund = fundamentals.build_payload(conn, row, as_of)
    sent = sentiment.build_payload(row, as_of, news.select_headlines(conn, row["symbol"], as_of))
    return {"quant": cache.payload_hash(dict(quant)) if quant else None,
            "fundamentals": cache.payload_hash(fund) if fund else None,
            "sentiment": cache.payload_hash(sent),
            "macro": cache.payload_hash(macro_out.model_dump(mode="json", exclude={"generated_at"})),
            "macro_llm": config.FEATURE_MACRO_LLM, "llm_enabled": config.LLM_ENABLED}


def _as_cached(v: Verdict) -> Verdict:
    """A verdict served from the cache: LIVE parts are reported as CACHED."""
    agents = [a.model_copy(update={"status": "CACHED"}) if a.status == "LIVE" else a for a in v.agents]
    status = "CACHED" if v.summary_status == "LIVE" else v.summary_status
    return v.model_copy(update={"agents": agents, "summary_status": status})


_refresh_lock = threading.Lock()
_last_refresh: dict[str, datetime] = {}  # ponytail: in-process, per instance; fine for one Render dyno


def _check_refresh(code: str, now: datetime) -> None:
    with _refresh_lock:
        last = _last_refresh.get(code)
        if last and now - last < REFRESH_INTERVAL:
            raise RateLimited(f"{code} was refreshed less than a minute ago; try again shortly.")
        _last_refresh[code] = now


# --- Entry point ---
def get_verdict(symbol: str, refresh: bool = False) -> Verdict:
    """The verdict for a KMI-30 stock. Raises NotInScope / RateLimited; LLM and agent failures never raise."""
    now = _now()
    with closing(queries.connect()) as conn:
        as_of = queries.meta(conn)["as_of_date"]
        row = queries.symbol(conn, symbol.strip().upper())
        if row is None or row["type"] != "STOCK":
            raise NotInScope(f"{symbol} has no verdict: verdicts cover KMI-30 stocks only.")
        code = row["symbol"]
        if refresh:
            _check_refresh(code, now)
        quant_row = _quant_row(conn, code, as_of)
        macro_out = _macro_output()
        inputs = _inputs(conn, row, as_of, quant_row, macro_out)

    key = ("verdict", code, as_of, f"{ROUTER_VERSION}+{SUMMARY_PROMPT_VERSION}", config.GEMINI_MODEL, inputs)
    if not refresh:
        for k in (key, ("verdict", code, as_of, cache.SEED, cache.SEED, {})):  # live key, then the seed
            if hit := cache.get(*k):
                return _as_cached(Verdict.model_validate(hit[0]))

    agents = [_safe("quant", lambda: quant_result(quant_row)),
              _safe("fundamentals", lambda: fundamentals.run(code)),
              _safe("sentiment", lambda: sentiment.run(code)),
              _safe("macro", lambda: macro.as_agent_result(macro_out))]
    combined = combine(agents)
    payload = summary_payload(code, as_of, combined)
    if combined["n_active"]:
        summary, summary_status = run_with_validation(_summary_call, payload, summary_template, SUMMARY_SCHEMA)
    else:
        summary, summary_status = summary_template(payload), "TEMPLATE"
    status = "TEMPLATE" if summary_status == "TEMPLATE" or any(a.status == "TEMPLATE" for a in agents) else "LIVE"
    verdict = Verdict(
        symbol=code, as_of_date=as_of, label=combined["label"], confidence=combined["confidence"],
        score=combined["score"], agreement=combined["agreement"], agents=combined["agents"],
        summary=summary["summary"], summary_status=summary_status, disclaimer=DISCLAIMER.format(as_of_date=as_of),
        cached_until=cache.expires_at("verdict", status, now), generated_at=now)
    cache.put(*key, verdict.model_dump(mode="json"), status)
    return verdict
