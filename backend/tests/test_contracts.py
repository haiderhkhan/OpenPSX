"""Contract tests (P0-04): every fixture matches its §4.3 model and every endpoint serves it."""
from __future__ import annotations

import json
import sqlite3
from contextlib import closing

import pytest
from fastapi.testclient import TestClient
from pydantic import BaseModel

from backend import config
from backend.main import app
from backend.schemas.chat import ChatAnswer, Transcription
from backend.schemas.common import ApiError, Health
from backend.schemas.insights import MacroOutput, ModelCard, QuantOutput, Verdict
from backend.schemas.market import ChangeSet, Compare, Overview, Prices, Returns, Universe

FIXTURE_MODELS: dict[str, type[BaseModel]] = {
    "health.json": Health,
    "universe.json": Universe,
    "overview.json": Overview,
    "prices.json": Prices,
    "changes.json": ChangeSet,
    "returns.json": Returns,
    "compare.json": Compare,
    "quant.json": QuantOutput,
    "model_card.json": ModelCard,
    "macro.json": MacroOutput,
    "verdict.json": Verdict,
    "chat.json": ChatAnswer,
    "transcribe.json": Transcription,
}

# (method, path, request kwargs, response model) — SCHEMA.md §4.2, all 13 endpoints
ENDPOINTS = [
    ("GET", "/api/health", {}, Health),
    ("GET", "/api/universe", {}, Universe),
    ("GET", "/api/overview?basis=fiscal", {}, Overview),
    ("GET", "/api/prices/OGDC?range=3M", {}, Prices),
    ("GET", "/api/changes/KMI30?basis=calendar", {}, ChangeSet),
    ("GET", "/api/returns/OGDC?freq=Q&basis=fiscal", {}, Returns),
    ("GET", "/api/compare/OGDC?range=1Y", {}, Compare),
    ("GET", "/api/quant/OGDC", {}, QuantOutput),
    ("GET", "/api/model/card", {}, ModelCard),
    ("GET", "/api/macro", {}, MacroOutput),
    ("GET", "/api/verdict/OGDC?refresh=true", {}, Verdict),
    ("POST", "/api/chat", {"json": {"question": "How has OGDC done this year?"}}, ChatAnswer),
    ("POST", "/api/transcribe", {"files": {"audio": ("q.webm", b"\x00\x01", "audio/webm")}}, Transcription),
]


@pytest.fixture(scope="module")
def client() -> TestClient:
    with TestClient(app) as c:  # runs the lifespan hook, with no .env and no DB
        yield c


def test_every_fixture_has_a_model() -> None:
    assert sorted(p.name for p in config.FIXTURES_DIR.glob("*.json")) == sorted(FIXTURE_MODELS)


@pytest.mark.parametrize("name", sorted(FIXTURE_MODELS))
def test_fixture_validates_and_round_trips(name: str) -> None:
    raw = json.loads((config.FIXTURES_DIR / name).read_text(encoding="utf-8"))
    model = FIXTURE_MODELS[name].model_validate(raw)
    assert model.model_dump(mode="json") == raw  # nothing dropped, renamed or reshaped


@pytest.mark.parametrize(("method", "path", "kwargs", "model"), ENDPOINTS, ids=[e[1] for e in ENDPOINTS])
def test_endpoint_returns_valid_contract(client: TestClient, method: str, path: str, kwargs: dict,
                                         model: type[BaseModel]) -> None:
    response = client.request(method, path, **kwargs)
    assert response.status_code == 200, response.text
    model.model_validate(response.json())


def test_openapi_lists_all_13_endpoints(client: TestClient) -> None:
    paths = client.get("/openapi.json").json()["paths"]
    operations = [(m.upper(), p) for p, ops in paths.items() for m in ops]
    assert len(operations) == 13
    assert client.get("/docs").status_code == 200


@pytest.mark.parametrize(("method", "path", "kwargs"), [
    ("GET", "/api/overview?basis=weekly", {}),
    ("GET", "/api/prices/OGDC?range=2Y", {}),
    ("POST", "/api/chat", {"json": {"question": ""}}),
    ("POST", "/api/chat", {"json": {"question": "x" * 301}}),
])
def test_bad_request_returns_api_error(client: TestClient, method: str, path: str, kwargs: dict) -> None:
    response = client.request(method, path, **kwargs)
    assert response.status_code == 400
    assert ApiError.model_validate(response.json()).error.code == "BAD_REQUEST"


def test_verdict_disclaimer_is_verbatim() -> None:
    verdict = Verdict.model_validate_json((config.FIXTURES_DIR / "verdict.json").read_text(encoding="utf-8"))
    assert verdict.disclaimer == (
        f"Educational outlook generated by models and AI from data up to {verdict.as_of_date.isoformat()}. "
        "Not investment advice or a recommendation to trade any security."
    )


def test_as_of_date_falls_back_to_fixture_without_db(monkeypatch: pytest.MonkeyPatch, tmp_path) -> None:
    monkeypatch.setattr(config, "DB_PATH", tmp_path / "missing.db")
    assert config.get_as_of_date() == "2026-10-09"
    assert not (tmp_path / "missing.db").exists()  # read-only open must not create the file


def test_as_of_date_reads_meta(monkeypatch: pytest.MonkeyPatch, tmp_path) -> None:
    db = tmp_path / "openpsx.db"
    with closing(sqlite3.connect(db)) as conn:
        conn.execute("CREATE TABLE meta (key TEXT PRIMARY KEY, value TEXT NOT NULL)")
        conn.execute("INSERT INTO meta VALUES ('as_of_date', '2026-10-08')")
        conn.commit()
    monkeypatch.setattr(config, "DB_PATH", db)
    assert config.get_as_of_date() == "2026-10-08"
