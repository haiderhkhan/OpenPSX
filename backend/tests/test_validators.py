"""§7 validators and the retry → template wrapper. No LLM: `call` is a scripted fake."""
from __future__ import annotations

import pytest

from backend.agents import llm, validators as v

PAYLOAD = {"symbol": "OGDC", "as_of_date": "2026-09-23", "ytd_pct": -5.234, "pe": 6.8, "p_up": 0.61, "eps": 31.25}
SCHEMA = {
    "type": "object",
    "properties": {
        "stance": {"type": "string", "enum": ["POSITIVE", "NEGATIVE", "NEUTRAL"]},
        "reasons": {"type": "array", "minItems": 1, "maxItems": 3, "items": {"type": "string", "maxLength": 200}},
    },
    "required": ["stance", "reasons"],
    "additionalProperties": False,
}
TEMPLATE = {"stance": "NEUTRAL", "reasons": ["Template reason."]}


def _out(*reasons: str) -> dict:
    return {"stance": "POSITIVE", "reasons": list(reasons)}


# --- Banned phrases ---
@pytest.mark.parametrize("text", [
    "Investment interest in OGDC grew.",
    "The sell-off in energy names eased.",
    "A selloff hit the market; investors waited.",
    "The company announced a buyback and a buy-back extension.",
    "Educational outlook generated by models and AI from data up to 2026-09-23. "
    "It is not investment advice and is not a signal to trade any security.",  # disclaimer (B-002)
    "Household spending rose.",
    "Fund holdings were unchanged.",
    "Each buyer met a seller.",
    "KMI-30 features hold 60% of the top-10 SHAP weight.",  # model-card wording (insights.py)
])
def test_allowed_wording_passes(text: str) -> None:
    assert v.banned_phrases(text) == []


@pytest.mark.parametrize("text", [
    "The target price is above the close.",
    "You should look at OGDC.",
    "Analysts would BUY here.",
    "We recommend caution.",
    "The stock will rise next week.",
    "Returns are guaranteed and risk-free.",
    "Limited upside remains.",
    "It may be wise to hold the stock.",
    "Investors could hold onto their shares.",
])
def test_advice_wording_fails(text: str) -> None:
    assert v.banned_phrases(text)


# --- Number grounding ---
@pytest.mark.parametrize("text", [
    "OGDC fell 5.2% this year.",           # sign ignored, rounded to the precision written
    "YTD return was -5.23%.",
    "P/E of 6.8 and EPS of 31.25.",
    "EPS is about 31.",
    "Up-move probability is 61%.",         # 0–1 payload value × 100 (D-37)
    "Data to 23 September 2026.",          # date parts from a payload string
    "OGDC vs the KMI-30 and KMI30 in FY26 Q1.",  # names and codes are not numbers
])
def test_grounded_numbers_pass(text: str) -> None:
    assert v.ungrounded_numbers(text, PAYLOAD) == []


@pytest.mark.parametrize(("text", "bad"), [
    ("OGDC rose 12% this year.", ["12%"]),
    ("P/E of 6.9.", ["6.9"]),
    ("EPS is 31.4.", ["31.4"]),
    ("Volume hit 1,250,000 shares.", ["1,250,000"]),
])
def test_ungrounded_number_fails(text: str, bad: list[str]) -> None:
    assert v.ungrounded_numbers(text, PAYLOAD) == bad


def test_100_percent_is_not_grounded_by_a_payload_1() -> None:
    assert v.ungrounded_numbers("All 100% of headlines were positive.", {"n_headlines": 1}) == ["100%"]
    assert v.ungrounded_numbers("Only 1 headline matched.", {"n_headlines": 1}) == []


# --- Schema + length ---
def test_schema_and_length_errors() -> None:
    assert v.validation_errors(_out("P/E of 6.8."), PAYLOAD, SCHEMA) == []
    assert v.validation_errors({"stance": "BULLISH", "reasons": []}, PAYLOAD, SCHEMA)
    assert v.validation_errors({"stance": "POSITIVE"}, PAYLOAD, SCHEMA)
    assert v.validation_errors({**_out("ok."), "extra": 1}, PAYLOAD, SCHEMA)
    assert v.validation_errors(_out("x" * 201), PAYLOAD, SCHEMA)
    assert v.validation_errors({"text": "x" * (v.MAX_TEXT_CHARS + 1)}, PAYLOAD)
    assert v.validation_errors({"n": True}, PAYLOAD, {"type": "object", "properties": {"n": {"type": "number"}}})


# --- run_with_validation ---
class Script:
    """Returns (or raises) the scripted outcomes in order and records each payload."""

    def __init__(self, *outcomes) -> None:
        self.outcomes, self.payloads = list(outcomes), []

    def __call__(self, payload: dict) -> dict:
        self.payloads.append(payload)
        out = self.outcomes.pop(0)
        if isinstance(out, Exception):
            raise out
        return out


def _template(payload: dict) -> dict:
    assert payload == PAYLOAD  # the template sees the original payload
    return TEMPLATE


def test_valid_output_is_live_with_one_call() -> None:
    call = Script(_out("P/E of 6.8."))
    assert v.run_with_validation(call, PAYLOAD, _template, SCHEMA) == (_out("P/E of 6.8."), "LIVE")
    assert call.payloads == [PAYLOAD]


def test_retry_with_error_then_live() -> None:
    call = Script(_out("You should look at the target price."), _out("P/E of 6.8."))
    assert v.run_with_validation(call, PAYLOAD, _template, SCHEMA) == (_out("P/E of 6.8."), "LIVE")
    retry = call.payloads[1]
    assert {k: retry[k] for k in PAYLOAD} == PAYLOAD
    assert "you should" in retry["previous_error"].lower()


def test_two_invalid_outputs_fall_back_to_template() -> None:
    call = Script(_out("Rose 12%."), _out("Rose 13%."))
    assert v.run_with_validation(call, PAYLOAD, _template, SCHEMA) == (TEMPLATE, "TEMPLATE")
    assert len(call.payloads) == 2
    assert "12%" in call.payloads[1]["previous_error"]


@pytest.mark.parametrize("exc", [llm.LLMDisabled("off"), llm.QuotaExhausted("429"), llm.LLMUnavailable("down")])
def test_llm_error_goes_straight_to_template(exc: llm.LLMError) -> None:
    call = Script(exc, _out("never used."))
    assert v.run_with_validation(call, PAYLOAD, _template, SCHEMA) == (TEMPLATE, "TEMPLATE")
    assert len(call.payloads) == 1


def test_llm_error_on_retry_falls_back_to_template() -> None:
    call = Script(_out("Rose 12%."), llm.QuotaExhausted("429"))
    assert v.run_with_validation(call, PAYLOAD, _template, SCHEMA) == (TEMPLATE, "TEMPLATE")
