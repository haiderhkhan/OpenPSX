"""P7-02 POST /api/chat: LIVE (mocked) → CACHED, TEMPLATE, REFUSED and ADVICE paths; never a 500."""
from __future__ import annotations

from pathlib import Path

import pytest

from backend import config
from backend.agents import llm, macro
from backend.agents.validators import banned_phrases
from backend.routing import chat_answer
from backend.schemas.chat import ChatAnswer


@pytest.fixture(autouse=True)
def env(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(config, "LLM_ENABLED", False)
    monkeypatch.setattr(macro, "MACRO_DIR", tmp_path / "macro")  # no weekly file: the macro template, computed now


class FakeLLM:
    """Answers chat_answer calls with `text(payload)`; counts the calls."""

    def __init__(self, monkeypatch: pytest.MonkeyPatch, text) -> None:
        self.calls, self.text = 0, text
        monkeypatch.setattr(config, "LLM_ENABLED", True)
        monkeypatch.setattr(llm, "generate_json", self)

    def __call__(self, agent, prompt_version, system, payload, schema, max_tokens):
        assert (agent, max_tokens) == ("chat_answer", 180)
        self.calls += 1
        return {"answer": self.text(payload)}


def ask(client, question: str) -> ChatAnswer:
    res = client.post("/api/chat", json={"question": question})
    assert res.status_code == 200, res.text
    return ChatAnswer.model_validate(res.json())


def test_live_answer_then_cached(client, monkeypatch: pytest.MonkeyPatch) -> None:
    fake = FakeLLM(monkeypatch, lambda p: f"OGDC moved {p['facts'][0]['value']} this calendar year.")
    first = ask(client, "How has OGDC done this year?")
    assert (first.intent, first.symbols, first.status) == ("CHANGE", ["OGDC"], "LIVE")
    assert first.answer.startswith("OGDC moved ") and first.facts and first.disclaimer is None
    again = ask(client, "How has OGDC done this year?")
    assert again.status == "CACHED" and again.answer == first.answer and fake.calls == 1


def test_template_when_the_llm_is_off(client) -> None:
    a = ask(client, "How has OGDC done this year?")
    assert a.status == "TEMPLATE"
    assert a.answer == " ".join(f"{f.label}: {f.value}." for f in a.facts)


@pytest.mark.parametrize("question", ["Should I buy Bitcoin?", "What about Tesla?", "Good luck with the demo!"])
def test_out_of_scope_is_refused(client, question: str) -> None:
    a = ask(client, question)
    assert (a.intent, a.status, a.facts, a.symbols, a.disclaimer) == ("OUT_OF_SCOPE", "REFUSED", [], [], None)
    assert a.answer.startswith("OPEN PSX only covers KMI-30 stocks and PSX-listed ETFs")


def test_advice_request_gets_the_template_and_the_verdict_facts(client) -> None:
    a = ask(client, "Should I buy OGDC?")
    assert (a.intent, a.status) == ("ADVICE_REQUEST", "TEMPLATE")
    assert a.answer.startswith("I can't tell you what to trade, but here is what the data and models show for OGDC")
    assert a.facts[0].label == "OGDC overall outlook" and a.disclaimer is not None
    assert banned_phrases(a.answer) == []


@pytest.mark.parametrize("bad", ["You should buy OGDC now.", "OGDC rose 99.9% this year."])
def test_llm_text_that_breaks_a_rule_falls_back_to_the_template(client, monkeypatch, bad: str) -> None:
    fake = FakeLLM(monkeypatch, lambda p: bad)
    a = ask(client, "How has OGDC done this year?")
    assert a.status == "TEMPLATE" and bad not in a.answer and fake.calls == 2  # one retry, then the template


def test_quant_answers_carry_the_disclaimer(client) -> None:
    a = ask(client, "What is the market regime right now?")
    assert a.intent == "QUANT" and a.facts[0].label == "KMI-30 market regime"
    assert a.disclaimer is not None and a.disclaimer.startswith("Educational outlook generated by models and AI")


def test_a_service_that_declines_gives_a_plain_note(client) -> None:
    a = ask(client, "What's the overall outlook for MZNPETF?")
    assert (a.intent, a.status, a.facts) == ("VERDICT", "TEMPLATE", [])
    assert "KMI-30 stocks only" in a.answer


@pytest.mark.parametrize("question", ["", "x" * 301])
def test_bad_question_is_400(client, question: str) -> None:
    res = client.post("/api/chat", json={"question": question})
    assert res.status_code == 400 and res.json()["error"]["code"] == "BAD_REQUEST"


def test_no_database_is_503_not_500(client, monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    monkeypatch.setattr(config, "DB_PATH", tmp_path / "missing.db")
    res = client.post("/api/chat", json={"question": "How has OGDC done this year?"})
    assert res.status_code == 503 and res.json()["error"]["code"] == "UPSTREAM"


def test_an_unexpected_fault_is_503_not_500(client, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(chat_answer, "answer", lambda q: 1 / 0)
    res = client.post("/api/chat", json={"question": "How has OGDC done this year?"})
    assert res.status_code == 503 and res.json()["error"]["code"] == "UPSTREAM"
